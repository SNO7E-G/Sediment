<?php

declare(strict_types=1);

namespace Sediment\Generator;

use Sediment\Analyzer\Finding;
use Sediment\Analyzer\WordPressCore;

/**
 * Generates a syntactically valid `uninstall.php` that removes what a plugin
 * leaves behind (M13).
 *
 * Safety first: only artifacts that are `verified` or `resolved`, not already
 * cleaned, and not WordPress core are emitted. `pattern` and `dynamic` keys are
 * never generated — deleting on a guess is exactly the failure this project
 * exists to avoid. The `{prefix}` token is rebuilt from `$wpdb->prefix`, never a
 * hardcoded prefix.
 */
final class UninstallGenerator
{
    private const PREFIX_TOKEN = '{prefix}';

    /**
     * @param list<Finding> $findings
     */
    public function generate(array $findings, string $pluginName = 'this plugin'): string
    {
        $options = [];      // key => delete function
        $siteOptions = [];  // key => true
        $tables = [];       // key => true
        $cron = [];         // hook => true
        $transients = [];   // key => delete function

        foreach ($findings as $finding) {
            if (!$this->isDeletable($finding)) {
                continue;
            }

            /** @var string $key (isDeletable guarantees non-null) */
            $key = $finding->key;

            match ($finding->type) {
                'option'    => $this->isSiteScoped($finding)
                    ? $siteOptions[$key] = true
                    : $options[$key] = true,
                'table'     => $tables[$key] = true,
                'cron'      => $cron[$key] = true,
                'transient' => $transients[$key] = $this->isSiteScoped($finding) ? 'delete_site_transient' : 'delete_transient',
                default     => null,
            };
        }

        ksort($options);
        ksort($siteOptions);
        ksort($tables);
        ksort($cron);
        ksort($transients);

        return $this->render($pluginName, $options, $siteOptions, $tables, $cron, $transients);
    }

    private function isDeletable(Finding $finding): bool
    {
        return $finding->key !== null
            && ($finding->confidence === Finding::CONFIDENCE_VERIFIED || $finding->confidence === Finding::CONFIDENCE_RESOLVED)
            && $finding->cleaned !== true
            && !WordPressCore::isCore($finding);
    }

    private function isSiteScoped(Finding $finding): bool
    {
        return str_contains($finding->function, 'site');
    }

    /**
     * @param array<string, true> $options
     * @param array<string, true> $siteOptions
     * @param array<string, true> $tables
     * @param array<string, true> $cron
     * @param array<string, string> $transients
     */
    private function render(string $pluginName, array $options, array $siteOptions, array $tables, array $cron, array $transients): string
    {
        $lines = [
            '<?php',
            '',
            '/**',
            ' * Uninstall routine generated by Sediment for ' . $pluginName . '.',
            ' *',
            ' * Removes the data this plugin leaves behind. Review before shipping:',
            ' * Sediment only emits artifacts it attributed with high confidence, so',
            ' * check the scan\'s coverage report for anything it could not resolve.',
            ' */',
            '',
            "if (!defined('WP_UNINSTALL_PLUGIN')) {",
            '    exit;',
            '}',
        ];

        if ($options !== [] || $siteOptions !== []) {
            $lines[] = '';
            $lines[] = '// Options';
            foreach (array_keys($options) as $key) {
                $lines[] = 'delete_option(' . var_export($key, true) . ');';
            }
            foreach (array_keys($siteOptions) as $key) {
                $lines[] = 'delete_site_option(' . var_export($key, true) . ');';
            }
        }

        if ($tables !== []) {
            $lines[] = '';
            $lines[] = '// Custom tables';
            $lines[] = 'global $wpdb;';
            foreach (array_keys($tables) as $key) {
                $lines[] = '$table = ' . $this->tableNameExpression($key) . ';';
                $lines[] = '$wpdb->query("DROP TABLE IF EXISTS `{$table}`");';
            }
        }

        if ($cron !== []) {
            $lines[] = '';
            $lines[] = '// Scheduled events';
            foreach (array_keys($cron) as $hook) {
                $lines[] = 'wp_clear_scheduled_hook(' . var_export($hook, true) . ');';
            }
        }

        if ($transients !== []) {
            $lines[] = '';
            $lines[] = '// Transients';
            foreach ($transients as $key => $function) {
                $lines[] = $function . '(' . var_export($key, true) . ');';
            }
        }

        return implode("\n", $lines) . "\n";
    }

    private function tableNameExpression(string $key): string
    {
        if (str_starts_with($key, self::PREFIX_TOKEN)) {
            $rest = substr($key, strlen(self::PREFIX_TOKEN));

            return $rest === '' ? '$wpdb->prefix' : '$wpdb->prefix . ' . var_export($rest, true);
        }

        return var_export($key, true);
    }
}
